/**
 * Fills in the round each carried-over prized seat won, from the "Prized Due"
 * column of the Advance Preparation sheets, and dates it by that round's
 * auction. The first member import read only "Prized Status", so these seats
 * knew that they were prized but not when.
 *
 * Writes a SQL file rather than talking to a database directly, so the same
 * statements can be run on the server without its password ever being on this
 * machine. The file holds group codes, seat numbers and due numbers only — no
 * names or phone numbers.
 *
 * Usage:
 *   npx tsx scripts/backfill-prized-due.ts                 # writes data/prized-due.sql
 *   npx tsx scripts/backfill-prized-due.ts --dir data/members --out data/prized-due.sql
 *   psql "$DATABASE_URL" -f data/prized-due.sql            # apply it (re-runnable)
 */

import ExcelJS from "exceljs"
import { readdir, writeFile } from "node:fs/promises"
import { extname, join } from "node:path"

const HEADER_ROW = 6
const FIRST_DATA_ROW = 7

const COL = { ticketNo: 8, group: 9, prizedDue: 16, prizedStatus: 17 } as const
const EXPECTED_HEADERS: Record<number, string> = {
  [COL.ticketNo]: "Ticket No",
  [COL.group]: "Group",
  [COL.prizedDue]: "Prized Due",
  [COL.prizedStatus]: "Prized Status",
}

function arg(name: string, fallback: string) {
  const i = process.argv.indexOf(name)
  return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback
}

function text(value: ExcelJS.CellValue): string {
  if (value === null || value === undefined) return ""
  if (typeof value === "object" && "result" in value) return String(value.result ?? "").trim()
  return String(value).trim()
}

const sqlText = (s: string) => `'${s.replace(/'/g, "''")}'`

async function main() {
  const dir = arg("--dir", "data/members")
  const out = arg("--out", "data/prized-due.sql")

  const files = (await readdir(dir)).filter((f) => extname(f) === ".xlsx").sort()
  // group + seat → due. A seat listed twice must agree with itself.
  const dues = new Map<string, { group: string; ticketNo: number; due: number }>()
  const conflicts: string[] = []
  let prizedWithoutDue = 0

  for (const file of files) {
    const wb = new ExcelJS.Workbook()
    await wb.xlsx.readFile(join(dir, file))
    const ws = wb.worksheets[0]

    const header = ws.getRow(HEADER_ROW)
    for (const [col, want] of Object.entries(EXPECTED_HEADERS)) {
      const got = text(header.getCell(Number(col)).value)
      if (got !== want) throw new Error(`${file}: column ${col} is "${got}", expected "${want}"`)
    }

    ws.eachRow((row, n) => {
      if (n < FIRST_DATA_ROW) return
      if (text(row.getCell(COL.prizedStatus).value).toLowerCase() !== "prized") return
      const group = text(row.getCell(COL.group).value)
      const ticketNo = Number(text(row.getCell(COL.ticketNo).value))
      const due = Number(text(row.getCell(COL.prizedDue).value))
      if (!group || !Number.isInteger(ticketNo)) return
      if (!Number.isInteger(due) || due < 1) {
        prizedWithoutDue++
        return
      }
      const key = `${group}#${ticketNo}`
      const seen = dues.get(key)
      if (seen && seen.due !== due) conflicts.push(`${group} seat ${ticketNo}: due ${seen.due} and ${due}`)
      else dues.set(key, { group, ticketNo, due })
    })
  }

  const values = [...dues.values()]
    .sort((a, b) => a.group.localeCompare(b.group) || a.ticketNo - b.ticketNo)
    .map((d) => `  (${sqlText(d.group)}, ${d.ticketNo}, ${d.due})`)

  // prizedOn is the date of that round's auction in the seat's own group.
  // Only seats already flagged prized are touched, so a stale sheet cannot
  // mark anyone prized; re-running sets the same values again.
  const sql = `-- Generated by scripts/backfill-prized-due.ts on ${new Date().toISOString()}
-- ${values.length} prized seats from ${files.length} sheets.
BEGIN;

UPDATE "ChitTicket" AS t
SET "prizedDue" = v.due,
    "prizedOn" = COALESCE(
      (SELECT a."auctionDate" FROM "Auction" a
        WHERE a."groupId" = t."groupId" AND a."installmentNo" = v.due),
      t."prizedOn")
FROM (VALUES
${values.join(",\n")}
) AS v(grp, ticket_no, due)
JOIN "ChitGroup" g ON g."group" = v.grp
WHERE t."groupId" = g.id
  AND t."ticketNo" = v.ticket_no
  AND t."isPrized";

COMMIT;

-- Check: prized seats still without a round.
SELECT count(*) AS prized_without_due FROM "ChitTicket" WHERE "isPrized" AND "prizedDue" IS NULL;
`

  await writeFile(out, sql)
  console.log(`Wrote ${out}: ${values.length} seats.`)
  if (prizedWithoutDue) console.log(`  ${prizedWithoutDue} prized rows had no due number; left as they are.`)
  if (conflicts.length) {
    console.log(`  ${conflicts.length} seats disagree between sheets; first value kept:`)
    for (const c of conflicts.slice(0, 20)) console.log(`    ${c}`)
  }
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
