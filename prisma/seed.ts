async function seedUsers() {
  // Give the sample Chit Admin the first branch so their scoped view is not empty.
  const firstBranch = ALL_GROUPS[0]?.branchName
  const usingFallbacks: string[] = []

  for (const spec of SEED_USERS) {
    const password = process.env[spec.passwordEnv] ?? spec.fallback
    if (!process.env[spec.passwordEnv]) usingFallbacks.push(spec.username)

    // Both the sample Chit Admin and the sample member sit in the first branch,
    // so the Chit Admin's scoped view has something in it and the member falls
    // inside their management scope.
    const branches =
      spec.role !== "SUPER_ADMIN" && firstBranch ? [firstBranch] : spec.branches

    // Upsert rather than delete: re-running the seed must not destroy accounts
    // that were created through the portal.
    await prisma.user.upsert({
      where: { username: spec.username },
      update: { name: spec.name, email: spec.email, role: spec.role, branches },
      create: {
        username: spec.username,
        name: spec.name,
        email: spec.email,
        role: spec.role,
        branches,
        passwordHash: await bcrypt.hash(password, 12),
      },
    })
  }

  if (usingFallbacks.length > 0) {
    console.warn(
      `\n  WARNING: seeded ${usingFallbacks.join(", ")} with the default password ` +
        `"ChangeMe123".\n  Change it before this reaches a public server, or set ` +
        `SEED_SUPER_ADMIN_PASSWORD / SEED_CHIT_ADMIN_PASSWORD / SEED_USER_PASSWORD.\n`
    )
  }
}

/**
 * Tables seeded with explicit ids. `createMany` with an id supplied does not
 * advance the identity sequence, so the next insert generated by the app would
 * collide with row 1. Re-pointing each sequence past its max fixes that.
 */
const EXPLICIT_ID_TABLES = ["Customer", "Employee", "ChitGroup", "Collection"]

async function resyncSequences() {
  for (const table of EXPLICIT_ID_TABLES) {
    // Table names come from the constant above, never from input.
    await prisma.$queryRawUnsafe(
      `SELECT setval(pg_get_serial_sequence('"${table}"', 'id'),
                     COALESCE((SELECT MAX(id) FROM "${table}"), 0) + 1,
                     false)`
    )
  }
}

