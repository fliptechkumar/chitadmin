/**
 * Every group gets its full roster up front, sized by ChitGroup.totalTickets.
 * Seat 1 is the foreman's own; the rest are filled from the applicant register
 * up to SEATED_PER_GROUP, leaving the remainder vacant so the assign flow has
 * somewhere to go.
 *
 * A group needs more members than it has held rounds, or every seat is prized
 * before the chit is half run and no later round has anyone left to bid.
 */
const SEATED_PER_GROUP = 12

async function seedTickets() {
  await prisma.chitTicket.deleteMany()

  const groups = await prisma.chitGroup.findMany({
    select: { id: true, branchName: true, totalTickets: true },
    orderBy: { id: "asc" },
  })

  let created = 0

  for (const [groupIndex, group] of groups.entries()) {
    const total = Math.max(1, group.totalTickets)

    const pool = await prisma.applicant.findMany({
      where: { branch: group.branchName, status: { not: "rejected" } },
      select: { id: true },
      orderBy: { id: "asc" },
    })

    // Each group starts at a different point in the register, so rosters
    // overlap the way real branches do rather than repeating one membership.
    const seats = Math.min(pool.length, SEATED_PER_GROUP, total - 1)
    const offset = pool.length === 0 ? 0 : (groupIndex * 5) % pool.length
    const applicants = Array.from(
      { length: seats },
      (_, i) => pool[(offset + i) % pool.length]
    )

    const route = await prisma.route.findFirst({
      where: { branch: group.branchName },
      select: { id: true },
    })

    await prisma.chitTicket.createMany({
      data: Array.from({ length: total }, (_, index) => {
        const ticketNo = index + 1
        const holder = ticketNo === 1 ? null : applicants[ticketNo - 2] ?? null

        return {
          groupId: group.id,
          ticketNo,
          isCompany: ticketNo === 1,
          applicantId: holder?.id ?? null,
          routeId: holder ? route?.id ?? null : null,
          assignedAt: holder ? new Date() : null,
        }
      }),
    })

    const taken = await prisma.chitTicket.count({
      where: { groupId: group.id, applicantId: { not: null } },
    })
    await prisma.chitGroup.update({
      where: { id: group.id },
      data: { members: taken, vacants: total - taken },
    })

    created += total
  }

  return created
}

/**
 * Instalment schedules for every seated ticket, with a spread of payment
 * states so the dues register shows paid, part-paid, pending and advance
 * rather than one uniform column.
 */
async function seedDues() {
  await prisma.auction.deleteMany()
  await prisma.ticketDue.deleteMany()

  const tickets = await prisma.chitTicket.findMany({
    where: { applicantId: { not: null }, isCompany: false },
    select: { id: true, ticketNo: true, group: { select: { amount: true, totalTickets: true } } },
  })

  const MONTHS = 12
  const today = new Date()
  let created = 0

  for (const [index, ticket] of tickets.entries()) {
    const base = Math.round(ticket.group.amount / ticket.group.totalTickets)

    const rows = Array.from({ length: MONTHS }, (_, month) => {
      const dueDate = new Date(today.getFullYear(), today.getMonth() - 5 + month, 10)
      // The pot climbs as the chit runs on and bidding softens; the dividend
      // each member earns shrinks with it, so the instalment creeps up.
      const prizeAmount = Math.round(ticket.group.amount * (0.72 + month * 0.02))
      const dividend = Math.max(150, Math.round((base * 0.18) - month * 90))
      const amountDue = base - dividend
      const elapsed = dueDate <= today

      // A repeatable spread rather than randomness, so re-seeding is stable.
      const behaviour = (index + month) % 7
      let amountPaid = 0
      if (elapsed) {
        if (behaviour === 3) amountPaid = Math.round(amountDue * 0.4)
        else if (behaviour === 5) amountPaid = 0
        else amountPaid = amountDue
      } else if (behaviour === 6) {
        // Paid ahead of the due date.
        amountPaid = amountDue
      }

      return {
        ticketId: ticket.id,
        installmentNo: month + 1,
        dueDate,
        amountDue,
        amountPaid,
        prizeAmount,
        dividend,
        // Settled dues were collected a few days after they fell due.
        paidOn:
          amountPaid > 0
            ? new Date(dueDate.getTime() + 3 * 24 * 60 * 60 * 1000)
            : null,
      }
    })

    await prisma.ticketDue.createMany({ data: rows })
    created += rows.length
  }

  return created
}

/**
 * A monthly auction per group. Rounds whose date has passed are marked held
 * with a winner drawn from that group's seats; the rest stay scheduled, so the
 * register shows both history and what is coming up.
 */
async function seedAuctions() {
  await prisma.auction.deleteMany()

  const groups = await prisma.chitGroup.findMany({
    select: { id: true, amount: true, totalTickets: true },
  })

  const MONTHS = 12
  const today = new Date()
  let created = 0

  for (const [groupIndex, group] of groups.entries()) {
    const seats = await prisma.chitTicket.findMany({
      where: { groupId: group.id, applicantId: { not: null }, isCompany: false },
      select: { id: true },
      orderBy: { ticketNo: "asc" },
    })

    // Auctions run on a fixed day of the month, staggered across groups so a
    // single day's register holds several rather than all of them at once.
    const day = 5 + ((groupIndex * 3) % 20)
    const hour = 9 + (groupIndex % 4)

    // A seat takes the pot once only, so winners are drawn from a pool that
    // shrinks each round. Once it is empty no further round can be held —
    // which is the rule the database now enforces too.
    const eligible = seats.map((s) => s.id)

    for (let month = 0; month < MONTHS; month++) {
      const auctionDate = new Date(today.getFullYear(), today.getMonth() - 5 + month, day)
      const winner = auctionDate <= today ? eligible.shift() ?? null : null
      // Past rounds with nobody left to bid stay unheld rather than being
      // recorded as completed with no winner.
      const held = winner !== null

      // Bidding softens as the chit runs on, so the discount falls and the
      // pot the winner takes grows.
      const discount = Math.max(2000, Math.round(group.amount * (0.28 - month * 0.02)))
      const prizeAmount = group.amount - discount
      const dividend = Math.round((discount * 0.95) / Math.max(1, group.totalTickets))

      await prisma.auction.create({
        data: {
          groupId: group.id,
          installmentNo: month + 1,
          auctionDate,
          auctionTime: `${String(hour).padStart(2, "0")}:${month % 2 ? "30" : "00"}`,
          status: held ? "completed" : "scheduled",
          winnerTicketId: winner,
          prizeAmount: held ? prizeAmount : 0,
          discount: held ? discount : 0,
          dividend: held ? dividend : 0,
        },
      })

      // isPrized is what the rest of the app reads, so it follows the result.
      if (winner !== null) {
        await prisma.chitTicket.update({
          where: { id: winner },
          data: { isPrized: true, prizedOn: auctionDate },
        })
      }

      created += 1
    }
  }

  return created
}

async function main() {
  // Clear existing rows so the seed is idempotent (collections first: FK).
  // Users and sessions are deliberately excluded — see seedUsers.
  await prisma.collection.deleteMany()
  await prisma.auction.deleteMany()
  await prisma.ticketDue.deleteMany()
  await prisma.chitTicket.deleteMany()
  await prisma.route.deleteMany()
  await prisma.applicant.deleteMany()
  await prisma.customer.deleteMany()
  await prisma.employee.deleteMany()
  await prisma.chitGroup.deleteMany()

  await prisma.customer.createMany({ data: CUSTOMERS })
  await prisma.employee.createMany({ data: EMPLOYEES })
  await prisma.chitGroup.createMany({ data: ALL_GROUPS })
  await prisma.collection.createMany({ data: COLLECTIONS })

  await resyncSequences()

  const applicantCount = await seedApplicants()
  await seedUsers()
  await seedCompany()
  // After users: routes record who created them.
  const routeCount = await seedRoutes()
  // After routes: seats reference a collection route.
  const ticketCount = await seedTickets()
  const dueCount = await seedDues()
  const auctionCount = await seedAuctions()

  console.log(
    `Seeded ${CUSTOMERS.length} customers, ${EMPLOYEES.length} employees, ` +
      `${ALL_GROUPS.length} groups, ${COLLECTIONS.length} collections, ` +
      `${applicantCount} applicants, ${routeCount} routes, ${ticketCount} tickets, ` +
      `${dueCount} dues, ${auctionCount} auctions, ${SEED_USERS.length} users.`
  )
}

main()
  .catch((e) => {
    console.error(e)
    process.exit(1)
  })
  .finally(async () => {
    await prisma.$disconnect()
  })
